def parse_topics_and_items(text: str):
    """Парсит темы и связанные с ними материалы"""
    lines = text.split('\n')
    topics = []
    current_topic = None
    current_items = []
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
        
        # Ищем заголовки тем (## Тема X. ...)
        topic_match = re.match(r'^##\s*Тема\s+(\d+)\.\s*(.*)', line)
        if topic_match:
            # Сохраняем предыдущую тему
            if current_topic and current_items:
                topics.append({
                    'number': current_topic['number'],
                    'name': current_topic['name'],
                    'items': current_items.copy()
                })
            # Начинаем новую тему
            current_topic = {
                'number': topic_match.group(1),
                'name': topic_match.group(2)
            }
            current_items = []
            continue
        
        # Ищем нумерованные пункты (1.1, 2.1 и т.д.)
        item_match = re.match(r'^(\d+(?:\.\d+)*)\.\s+(.*)', line)
        if item_match and current_topic:
            current_items.append({
                'number': item_match.group(1),
                'text': item_match.group(2)
            })
    
    # Добавляем последнюю тему
    if current_topic and current_items:
        topics.append({
            'number': current_topic['number'],
            'name': current_topic['name'],
            'items': current_items.copy()
        })
    
    return topics

def classify_item(item: dict) -> str:
    """Определяет тип пункта (определение, теорема, задача)"""
    num = item['number']
    text = item['text'].lower()
    
    # Определения (1.x)
    if num.startswith('1.'):
        return 'definition'
    
    # Теоремы (2.x с ключевыми словами)
    if num.startswith('2.'):
        theorem_keywords = ['теорем', 'докажите', 'сформулируйте', 'доказательство']
        for kw in theorem_keywords:
            if kw in text:
                return 'theorem'
        return 'problem'
    
    return 'problem'

