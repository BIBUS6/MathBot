async def random_topic(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not topics:
        await update.message.reply_text("❌ Темы не найдены")
        return
    topic = random.choice(topics)
    items_preview = []
    for item in topic['items'][:3]:
        preview = item['text'][:60] + "..." if len(item['text']) > 60 else item['text']
        items_preview.append(f"  • {item['number']}. {preview}")
    
    preview_text = "\n".join(items_preview)
    if len(topic['items']) > 3:
        preview_text += f"\n  ... и ещё {len(topic['items'])-3} материалов"
    
    await update.message.reply_text(
        f"📚 **Тема {topic['number']}: {topic['name']}**\n\n"
        f"📌 Всего материалов в теме: {len(topic['items'])}\n\n"
        f"📋 Примеры:\n{preview_text}",
        parse_mode="Markdown"
    )

